// Build-time generator: renders 2D structures + molecular formulas with
// OpenChemLib and writes them as static data to src/data/structures.generated.js
// so the browser bundle needs no chemistry library.
//
// Run:  node scripts/gen-structures.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import OCL from 'openchemlib';
import { SMILES, STRUCT_NOTE } from '../src/data/smiles.js';

const out = {};
for (const [id, smiles] of Object.entries(SMILES)) {
  const mol = OCL.Molecule.fromSmiles(smiles);
  const mf = mol.getMolecularFormula();
  let svg = mol.toSVG(360, 220, `mol-${id}`, {
    suppressChiralText: true,
    suppressESR: true,
    autoCrop: true,
    autoCropMargin: 10,
    strokeWidth: 1.4,
  });
  svg = svg.replace(/rgb\(0,0,0\)/g, 'currentColor');
  svg = svg.replace(/(<svg[^>]*?)\s+width="[^"]*"\s+height="[^"]*"/, '$1 width="100%" height="100%"');
  out[id] = {
    svg,
    formula: mf.formula,
    mw: +mf.relativeWeight.toFixed(2),
    note: STRUCT_NOTE[id] || null,
  };
  console.log(id.padEnd(14), mf.formula.padEnd(22), mf.relativeWeight.toFixed(2));
}

const __dirname = dirname(fileURLToPath(import.meta.url));
const dest = resolve(__dirname, '../src/data/structures.generated.js');
const banner =
  '// AUTO-GENERATED by scripts/gen-structures.mjs — do not edit by hand.\n' +
  '// Pre-rendered 2D structures (OpenChemLib). Carbon bonds use currentColor\n' +
  '// so a single SVG works in both light and dark themes.\n\n';
writeFileSync(dest, banner + 'export const STRUCTURES = ' + JSON.stringify(out) + ';\n');
console.log('\nWrote', dest);
